#!/usr/bin/env python3
"""Ops diagnosis Agent — Day 1 skeleton: AgentState (plan Ch.4).

Fields follow the plan's state table exactly. The state object is a plain
dataclass so it serialises to JSON for the file checkpointer (plan Ch.4:
"Checkpointer 持久化状态，进程重启后能从 human_approval 处恢复").
No LLM, no LangGraph dependency: the graph runner in graph.py executes the
same node order and conditional edges, and uses real LangGraph when it is
installed (see graph.py build_graph()).
"""
from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from typing import Any

from .diagnosis import Diagnosis

# Plan Ch.4: at most 2 evidence-collection rounds, at most 1 verify retry.
MAX_EVIDENCE_ROUNDS = 2
MAX_VERIFY_RETRIES = 1
# Plan Ch.6 module 2 / Ch.5: one event carries at most 10 key evidence
# items, each timestamped; a read-only tool that does not answer within
# 10s is treated as degraded, not fatal (Day 4).
MAX_EVIDENCE_ITEMS = 10
EVIDENCE_TOOL_TIMEOUT_S = 10.0
# Plan Ch.4 / Ch.6 module 4: below this confidence, collect one more round
# of evidence instead of guessing a root cause.
DIAGNOSE_CONFIDENCE_THRESHOLD = 0.5


@dataclass
class Evidence:
    source: str          # e.g. "logs", "metrics", "runbook", "status"
    timestamp: str
    summary: str
    ref: str             # chunk_id / log id / metric name — traceable origin


@dataclass
class Hypothesis:
    cause: str
    confidence: float
    evidence_refs: list[str] = field(default_factory=list)


@dataclass
class PlanStep:
    step: str
    tool: str
    risk: str            # "low" | "high"
    rollback: str = ""   # required for high-risk steps (plan Ch.6 module 5)
    result: str = ""
    # Day 7: a rollback is an explicit plan step, not a text note.
    # is_rollback steps are generated by make_plan() immediately after
    # the high-risk step they undo, are skipped by execute() in the
    # normal flow, and only run on the Day 9 failure path. rollback_of
    # names the high-risk step's text (the 1:1 pairing key).
    is_rollback: bool = False
    rollback_of: str = ""
    # Day 7: where the step comes from — a runbook chunk ref collected
    # in state.evidence (e.g. "runbook:<chunk_id>"), or the literal
    # marker "建议人工判断" when no manual/case supports the step.
    # "" only occurs on incidents created before Day 7; from_dict
    # tolerates the missing keys via these defaults, so old state.json
    # files still load.
    source: str = ""
    # Day 9: arguments the tool needs beyond (state, service), e.g.
    # {"replicas": 2} for a scale_service rollback, or {"key": ...,
    # "value": ...} for an update_config rollback (filled at rollback
    # time from the config snapshot). Default {} so pre-Day-9
    # state.json files still load via from_dict, and execute() calls
    # tools with **params — empty params means "service only", exactly
    # the Day 1–8 call shape, so the normal path is unchanged.
    params: dict[str, Any] = field(default_factory=dict)


@dataclass
class AgentState:
    incident_id: str
    alert: dict[str, Any] = field(default_factory=dict)
    category: str = ""
    severity: str = ""
    evidence: list[Evidence] = field(default_factory=list)
    # Day 4: evidence sources that timed out / failed in the latest
    # collection round (e.g. "runbook: timeout>10.0s"). Diagnosis continues
    # with the evidence that was gathered; the gaps are shown in the report.
    evidence_gaps: list[str] = field(default_factory=list)
    hypotheses: list[Hypothesis] = field(default_factory=list)
    # Day 5: validated structured diagnosis output (diagnosis/v1) from the
    # diagnose node — the contract the eval harness scores on Days 11–12.
    # None for incidents created before Day 5; from_dict tolerates that.
    diagnosis: Diagnosis | None = None
    # Day 5: LLM engine failures recorded loudly (no key, timeout, bad
    # JSON, schema violation) — each entry notes the failure and the
    # fallback to the rule engine. Empty when the rule engine ran
    # directly (no key configured) or the LLM engine succeeded.
    diagnosis_engine_failures: list[str] = field(default_factory=list)
    plan: list[PlanStep] = field(default_factory=list)
    risk_level: str = "low"          # "low" | "high"
    approval: dict[str, Any] = field(default_factory=dict)
    exec_result: list[dict[str, Any]] = field(default_factory=list)
    retry_count: int = 0             # evidence rounds used
    verify_retries: int = 0
    status: str = "new"              # new|running|awaiting_approval|approved|
                                     # rejected|executing|verifying|done|closed
    trace: list[dict[str, Any]] = field(default_factory=list)
    tool_audit: list[dict[str, Any]] = field(default_factory=list)
    # Demo-service snapshot, persisted with the state so a resume in a new
    # process sees the same service state (Day 1: in-memory demo only).
    demo_service: dict[str, Any] = field(default_factory=dict)
    report_path: str = ""
    created_at: float = field(default_factory=time.time)
    # Day 8: expire closes an incident that waited too long at
    # human_approval. closed_reason records why (e.g. timeout) and
    # closed_at the epoch time it was closed; both default to empty/0
    # so pre-Day-8 state.json files still load via from_dict.
    closed_reason: str = ""
    closed_at: float = 0.0
    # Day 9: the failure path. rollback_triggered is set when execute()
    # hit a failure after at least one high-risk step had succeeded and
    # ran the paired rollbacks; verify() and the report use it to tell
    # "recovered after rollback" apart from a normal recovery.
    # rolled_back_steps names the forward high-risk steps whose paired
    # rollback already ran — make_plan() skips them on the verify-retry
    # rebuild, so a rolled-back change is never re-executed (same
    # standing-instruction mechanism as Day 8's dropped_steps).
    rollback_triggered: bool = False
    rolled_back_steps: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "AgentState":
        d = dict(d)
        d["evidence"] = [Evidence(**e) for e in d.get("evidence", [])]
        d["hypotheses"] = [Hypothesis(**h) for h in d.get("hypotheses", [])]
        if d.get("diagnosis") is not None:
            d["diagnosis"] = Diagnosis.from_dict(d["diagnosis"])
        d["plan"] = [PlanStep(**p) for p in d.get("plan", [])]
        return cls(**d)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=2)
